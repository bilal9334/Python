def calculate_sum(a: int, b: int) -> int:
    """
    Calculate and return the sum of two numbers.

    :param a: The first `int`.
    :param b: The second `int`.
    :return: The sum of `a` and `b`

    Example:
    >> calculate_sum(4, 5)
    9
    """
    return a + b


result = calculate_sum(4, 5)
print(result)
